// R5.2-B (2026-07-14): emit `::L::` markers for each top-level
// LabelDeclStmt in `body`, at the current indent. The caller
// (emitWhileStmt / emitForStmt) invokes this AFTER writing the
// loop's `end` keyword, so the label lands at the same indent
// as the loop header — i.e. immediately AFTER the loop. This
// is what makes `break :L` work: the compiled `goto L` jumps to
// the label at loop end, falling out of the loop.
//
// We do NOT emit the label inside the loop body because Lua
// 5.2+ forbids re-declaring a label in the same block (a
// loop's body is one block across all iterations).
//
// Implementation note: the body comes in as `const
// std::vector<StmtPtr>&` (the loop's body field is read-only).
// Copying `unique_ptr` is forbidden, so we cannot build a
// "stripped body" vector — the caller walks the body twice
// (emitBlockSkipLabels iterates the body and skips labels;
// this helper iterates the body and emits only labels).
void LuaCodegen::hoistLabelsFromBody(const std::vector<StmtPtr>& body)
{
    for (const auto& s : body) {
        if (auto* ld = dynamic_cast<const LabelDeclStmt*>(s.get())) {
            // S5 ED-03 (2026-07-15): hoisted labels are anchored to
            // the enclosing loop's sourceLoc (set by emitStmt() before
            // dispatching into emitWhileStmt / emitForStmt). The label
            // sourceLoc itself is irrelevant for runtime panic
            // translation — a `goto L` that lands on a hoisted label
            // is a Logia `break :L` source line, which is the loop's
            // sourceLoc.
            std::string out;
            out += "::";
            out += ld->name;
            out += "::";
            writeLine(out);
        }
    }
}

LuaCodegen::LuaCodegen(LuaCodegenOptions options)
    : _options(std::move(options)) {}

LuaCodegenResult LuaCodegen::generate(const Program& program)
{
    LuaCodegenResult result;
    _errors.clear();
    _out.clear();
    _indent = 0;
    _tmpCounter = 0;

    // S5 ED-03 (2026-07-15): preamble is codegen-internal (no Logia
    // source anchor). writeNoAnchor tracks the line count for the
    // source map without recording a user-anchored Logia loc — a
    // runtime panic on these lines is structurally a codegen bug.
    std::string headerComment = "-- Auto-generated by AYLuaCodegen from ";
    headerComment += _options.scriptName.empty() ? std::string("Logia source") : _options.scriptName;
    writeNoAnchor(headerComment);
    writeNoAnchor("local M = {}");
    writeBlankLine();

    // S2.5: a `.logia` file produces exactly one module (one `script`
    // block). Multiple scripts in one file generate multiple modules —
    // call once per script from the loader. For now, generate only the
    // first script (the parser produces a single `ScriptDecl` per file
    // in practice; the loader can re-enter `generate` with another
    // Program if needed).
    if (program.scripts.empty()) {
        CompilerError err;
        err.code = ErrorCode::InvalidStatement;
        err.message = "Logia file contains no script declaration";
        err.line = 0;
        err.column = 0;
        _errors.push_back(err);
    } else {
        emitScript(*program.scripts[0]);
    }

    // S5 ED-03 (2026-07-15): epilogue is also codegen-internal. Use
    // the same writeNoAnchor + writeBlankLine pair as the preamble
    // so the bridge treats these lines as untranslatable.
    writeBlankLine();
    writeNoAnchor("return M");

    result.errors = _errors;
    result.source = _out;
    // S5 ED-03 (2026-07-15): per-line Lua → Logia source map. The
    // header (`local M = {}` on Lua line 1) and footer (`return M`
    // on the last line) are NOT anchored — they have no Logia
    // source location (codegen preamble/epilogue). Their
    // corresponding entries in `_sourceMap.luaLineToSource` are
    // default-constructed SourceLocation with `line == 0`, which
    // the bridge's translation treats as "untranslatable" (no
    // source-mapped Logia line). A runtime panic on those lines is
    // a codegen bug, not a user-source bug, so untranslatable is
    // the correct behavior.
    result.sourceMap = _sourceMap;
    result.success = _errors.empty();
    return result;
}

