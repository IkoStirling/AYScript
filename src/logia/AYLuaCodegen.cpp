void LuaCodegen::line(const std::string& s)
{
    indent();
    _out += s;
    _out += "\n";
}

void LuaCodegen::indent()
{
    for (int i = 0; i < _indent; ++i) _out += "    ";
}

void LuaCodegen::dedent()
{
    if (_indent > 0) --_indent;
}

std::string LuaCodegen::escapeString(const std::string& s) const
{
    std::string out;
    out.reserve(s.size() + 2);
    out += '"';
    for (char c : s) {
        switch (c) {
        case '"':  out += "\\\""; break;
        case '\\': out += "\\\\"; break;
        case '\n': out += "\\n";  break;
        case '\r': out += "\\r";  break;
        case '\t': out += "\\t";  break;
        default:
            if (static_cast<unsigned char>(c) < 0x20) {
                char buf[8];
                std::snprintf(buf, sizeof(buf), "\\x%02X", static_cast<unsigned char>(c));
                out += buf;
            } else {
                out += c;
            }
        }
    }
    out += '"';
    return out;
}

void LuaCodegen::errorAt(const Token& tok, const std::string& message)
{
    CompilerError err;
    err.code = ErrorCode::InvalidStatement;
    err.message = message;
    err.line = tok.line;
    err.column = tok.column;
    _errors.push_back(err);
}

